    #[test]
    fn a_generic_impl_belongs_to_its_type_and_trait_arguments_stay() {
        let d = |name: &str, suffix: Suffix| scip::types::Descriptor {
            name: name.to_string(),
            suffix: protobuf::EnumOrUnknown::new(suffix),
            ..Default::default()
        };
        let got = shape(&[
            d("m", Suffix::Namespace),
            d("impl", Suffix::Type),
            d("Ctx<'a>", Suffix::TypeParameter),
            d("From<String>", Suffix::TypeParameter),
            d("from", Suffix::Method),
        ]);
        assert_eq!(
            got,
            Shape::Function {
                module: vec!["m".to_string()],
                owner: Some("Ctx".to_string()),
                trait_name: Some("From<String>".to_string()),
                name: "from".to_string(),
            }
        );
    }

    #[test]
