    /// 17     fn helper() { super::util(); }
    /// 18 }
    const LIB: &str = "use crate::helpers::util;\npub struct S;\nimpl S {\n    pub fn a(&self) {\n        self.b();\n        util();\n    }\n    fn b(&self) {}\n}\nimpl Tr for S {\n    fn t(&self) { self.a(); }\n}\npub trait Tr { fn t(&self); }\npub fn util() {}\n#[cfg(test)]\nmod tests {\n    fn helper() { super::util(); }\n}\n";

    fn build(extra: impl FnOnce(&mut Document)) -> (Dir, Model) {
        let d = Dir::new();
        d.write("x/src/lib.rs", LIB);
        let mut doc = Document {
            relative_path: "x/src/lib.rs".to_string(),
            ..Default::default()
        };
        def(&mut doc, "S#", 2, ScipKind::Struct, "pub struct S");
        def(
            &mut doc,
            "impl#[S]a().",
            4,
            ScipKind::Method,
            "pub fn a(&self)",
        );
        def(&mut doc, "impl#[S]b().", 8, ScipKind::Method, "fn b(&self)");
        def(
            &mut doc,
            "impl#[S][Tr]t().",
            11,
            ScipKind::Method,
            "fn t(&self)",
        );
        def(&mut doc, "Tr#", 13, ScipKind::Trait, "pub trait Tr");
        def(
            &mut doc,
            "Tr#t().",
            13,
            ScipKind::TraitMethod,
            "pub fn t(&self)",
        );
        def(&mut doc, "util().", 14, ScipKind::Function, "pub fn util()");
        def(
            &mut doc,
            "tests/helper().",
            17,
            ScipKind::Function,
            "fn helper()",
        );
        reference(&mut doc, "util().", 1); // the `use`
        reference(&mut doc, "impl#[S]b().", 5);
        reference(&mut doc, "util().", 6);
        reference(&mut doc, "impl#[S]a().", 11);
        reference(&mut doc, "util().", 17); // from test code
        extra(&mut doc);
        let index = Index {
            documents: vec![doc],
            ..Default::default()
        };
        let sources = Sources::scan(d.path(), &["x".to_string()]);
        let model = Model::build(&index, crate_x(), &sources, &BTreeSet::new());
        (d, model)
    }

    fn calls(m: &Model) -> Vec<(String, String, usize)> {
        m.calls
            .iter()
            .map(|(&(a, b), &n)| (m.functions[a].id.clone(), m.functions[b].id.clone(), n))
            .collect()
    }

    #[test]
    fn every_function_shape_gets_its_owner_trait_and_id() {
        let (_d, m) = build(|_| {});
        let ids: Vec<&str> = m.functions.iter().map(|f| f.id.as_str()).collect();
        assert_eq!(
            ids,
            ["x::S::a", "x::S::b", "x::S::t@Tr", "x::Tr::t", "x::util"]
        );
        let t = m.functions.iter().find(|f| f.id == "x::S::t@Tr").unwrap();
        assert_eq!(
            (t.owner.as_deref(), t.trait_name.as_deref(), t.vis),
            (Some("S"), Some("Tr"), Vis::Trait)
        );
        let b = m.functions.iter().find(|f| f.name == "b").unwrap();
        assert_eq!(b.vis, Vis::Private);
        assert_eq!(b.docs.as_deref(), Some("Docs of impl#[S]b().."));
    }

    #[test]
    fn calls_are_placed_in_the_function_that_makes_them() {
        let (_d, m) = build(|_| {});
        assert_eq!(
            calls(&m),
            [
                ("x::S::a".to_string(), "x::S::b".to_string(), 1),
                ("x::S::a".to_string(), "x::util".to_string(), 1),
                ("x::S::t@Tr".to_string(), "x::S::a".to_string(), 1),
            ]
        );
    }

